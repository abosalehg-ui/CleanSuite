using System.IO.Compression;
using System.Text;
using CleanSuite.Junk;
using CleanSuite.Restore;
using CleanSuite.Safety;
using Microsoft.Win32;

namespace CleanSuite.Tests;

/// <summary>Restore tool: catalog, the original's dup and registry zips, .reg import rules (temp folders and a private hive only).</summary>
public class RestoreToolTests
{
    private sealed class FakeBin : IRecycleBin
    {
        public IReadOnlyList<string> Recycle(IReadOnlyList<string> paths, bool silent)
        {
            foreach (var p in paths) File.Delete(p);
            return Array.Empty<string>();
        }
    }

    [Fact]
    public void Catalog_finds_every_kind_and_parses_the_time_from_the_name()
    {
        using var sb = new Sandbox();
        foreach (var n in new[] { "Jnk 2026_10_21_03_07_09_PM.zip", "Dup 2026_10_20_11_00_00_AM.zip", "Reg 2026_10_19_12_30_00_AM.zip",
                                  "Reg 2026_10_18_01_02_03_PM.reg", "notes.txt", "other.zip" })
            File.WriteAllBytes(Path.Combine(sb.Root, n), [0]);
        var list = BackupCatalog.List([sb.Root]);
        Assert.Equal(new[] { BackupKind.JunkFiles, BackupKind.DuplicateFiles, BackupKind.RegistryZip, BackupKind.Registry }, list.Select(b => b.Kind));
        Assert.Equal(new DateTime(2026, 10, 21, 15, 7, 9), list[0].Created);
        Assert.Equal(new DateTime(2026, 10, 19, 0, 30, 0), list[2].Created);                 // 12 AM = midnight
        Assert.Null(BackupCatalog.CreatedFrom("backup.zip"));
    }

    [Fact]
    public void Original_duplicate_zip_restores_from_the_entry_comment_without_overwriting()
    {
        using var sb = new Sandbox();
        var zipPath = Path.Combine(sb.Root, "Dup 2026_10_20_11_00_00_AM.zip");
        var target = Path.Combine(sb.Root, @"restored\song.mp3");
        var existing = Path.Combine(sb.Root, @"restored\keep.txt");
        Directory.CreateDirectory(Path.GetDirectoryName(existing)!);
        File.WriteAllText(existing, "current");
        using (var zip = ZipFile.Open(zipPath, ZipArchiveMode.Create))
        {
            var e = zip.CreateEntry("song.mp3");
            using (var s = e.Open()) s.Write("music"u8);
            e.Comment = target;
            var k = zip.CreateEntry("keep.txt");
            using (var s = k.Open()) s.Write("old"u8);
            k.Comment = existing;
        }
        ZipComment.Set(zipPath, "\nThis is an Ace Utilities Backup file; not a normal zip file. \nPlease DO NOT EDIT this file.");

        var entries = JunkBackupArchive.List(zipPath);
        Assert.Equal(new[] { target, existing }.OrderBy(x => x), entries.Select(x => x.OriginalPath).OrderBy(x => x));
        var r = JunkBackupArchive.RestoreEntries(zipPath, entries, protectedPaths: new ProtectedPaths(), journalBase: Path.Combine(sb.Root, "_j"));
        Assert.Equal(1, r.Restored);
        Assert.Equal("music", File.ReadAllText(target));
        Assert.Equal("current", File.ReadAllText(existing));                                  // never overwritten
        Assert.True(BackupCatalog.List([sb.Root]).Single().FromOriginal);
    }

    [Fact]
    public void Original_registry_zip_and_reg_files_restore_only_additions()
    {
        using var sb = new Sandbox();
        using var roots = new AppHiveRegistryRoots(Path.Combine(sb.Root, "t.hiv"));
        using (var k = roots.Root(RegHive.CurrentUser).CreateSubKey(@"Software\Keep")) k.SetValue("stay", "yes");
        var zipPath = Path.Combine(sb.Root, "Reg 2026_10_19_12_30_00_AM.zip");
        using (var zip = ZipFile.Open(zipPath, ZipArchiveMode.Create))
        {
            var e = zip.CreateEntry("0");
            using (var s = e.Open())
            {
                var text = "Windows Registry Editor Version 5.00\r\n\r\n[HKEY_CURRENT_USER\\Software\\Vendor\\App]\r\n\"Path\" = \"C:\\\\Old\\\\app.exe\"\r\n";
                var bytes = Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes(text)).ToArray();
                s.Write(bytes);
            }
            e.Comment = @"2HKEY_CURRENT_USER\Software\Vendor\App\Path";
        }
        var items = BackupCatalog.RegistryZipItems(zipPath);
        Assert.False(Assert.Single(items).IsKey);
        Assert.Equal(@"HKEY_CURRENT_USER\Software\Vendor\App\Path", items[0].Item);

        var reg = Path.Combine(sb.Root, "Reg 2026_10_18_01_02_03_PM.reg");
        File.WriteAllText(reg, "REGEDIT4\r\n\r\n[-HKEY_CURRENT_USER\\Software\\Keep]\r\n\r\n[HKEY_CURRENT_USER\\Software\\Keep]\r\n\"stay\"=-\r\n\"new\"=\"v\"\r\n");
        foreach (var b in BackupCatalog.List([sb.Root]))
            Assert.Empty(BackupCatalog.RestoreRegistry(b, roots, Path.Combine(sb.Root, "_j")).Errors);

        using (var k = roots.Root(RegHive.CurrentUser).OpenSubKey(@"Software\Vendor\App")!) Assert.Equal(@"C:\Old\app.exe", k.GetValue("Path"));
        using (var k = roots.Root(RegHive.CurrentUser).OpenSubKey(@"Software\Keep")!)
        {
            Assert.Equal("yes", k.GetValue("stay"));                                             // deletion lines ignored
            Assert.Equal("v", k.GetValue("new"));
        }
    }

    [Fact]
    public void Original_reg_format_with_spaced_default_and_typed_hex_values_imports()
    {
        using var sb = new Sandbox();
        using var roots = new AppHiveRegistryRoots(Path.Combine(sb.Root, "t.hiv"));
        var reg = Path.Combine(sb.Root, "Reg 2026_10_18_01_02_03_PM.reg");
        File.WriteAllText(reg, "Windows Registry Editor Version 5.00\r\n\r\n[HKEY_CURRENT_USER\\Software\\Classes\\.txt\\OpenWithProgids]\r\n" +
                               "@ = \"Steam.exe\"\r\n\"txtfile\" = hex(0):\r\n\"big\" = hex(b):01,00,00,00,00,00,00,00\r\n", Encoding.Unicode);
        var r = BackupCatalog.RestoreRegistry(BackupCatalog.List([sb.Root]).Single(), roots, Path.Combine(sb.Root, "_j"));
        Assert.Empty(r.Errors);
        Assert.Equal(3, r.Values);
        using var k = roots.Root(RegHive.CurrentUser).OpenSubKey(@"Software\Classes\.txt\OpenWithProgids")!;
        Assert.Equal("Steam.exe", k.GetValue(""));
        Assert.Equal(RegistryValueKind.None, k.GetValueKind("txtfile"));
        Assert.Equal(RegistryValueKind.QWord, k.GetValueKind("big"));
        Assert.Equal(1L, k.GetValue("big"));
    }

    [Fact]
    public void Deleting_backups_goes_to_the_recycle_bin()
    {
        using var sb = new Sandbox();
        var p = Path.Combine(sb.Root, "Jnk 2026_10_21_03_07_09_PM.zip");
        File.WriteAllBytes(p, [0]);
        var (removed, failed) = BackupCatalog.Delete(BackupCatalog.List([sb.Root]), new FakeBin(), Path.Combine(sb.Root, "_j"));
        Assert.Equal(1, removed);
        Assert.Empty(failed);
        Assert.False(File.Exists(p));
    }
}
