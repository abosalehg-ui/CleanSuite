using System.Runtime.InteropServices;
using System.IO.Compression;
using CleanSuite.Junk;
using CleanSuite.Safety;
using Xunit;

namespace CleanSuite.Tests;

public class RemoverTests
{
    private sealed class FakeRecycleBin : IRecycleBin
    {
        public List<string> Received { get; } = new();
        public string Store { get; } = Path.Combine(Path.GetTempPath(), "CleanSuiteTests", "bin_" + Guid.NewGuid().ToString("N"));
        public IReadOnlyList<string> Recycle(IReadOnlyList<string> paths, bool silent)
        {
            Directory.CreateDirectory(Store);
            Received.AddRange(paths);
            foreach (var p in paths) File.Move(p, Path.Combine(Store, Guid.NewGuid().ToString("N")));
            return Array.Empty<string>();
        }
    }

    private static JunkItem Item(string path) =>
        new(path, Path.GetFileName(path), Path.GetDirectoryName(path)!, new FileInfo(path).Length, JunkReason.JunkType, "Junk", 0);

    private static JunkRemover Remover(Sandbox sb, IRecycleBin? bin = null) =>
        new(bin ?? new FakeRecycleBin(), new ProtectedPaths(), Path.Combine(sb.Root, "_journal"));

    [Fact]
    public void Permanent_mode_deletes_and_journals()
    {
        using var sb = new Sandbox();
        var a = sb.File("a.tmp", 100);
        var b = sb.File("b.tmp", 50);
        File.SetAttributes(b, FileAttributes.ReadOnly);
        var res = Remover(sb).Remove(new JunkRemovalRequest { Items = new[] { Item(a), Item(b) }, Mode = RemovalMode.Permanent });
        Assert.Equal(2, res.Deleted);
        Assert.Equal(150, res.BytesFreed);
        Assert.False(File.Exists(a) || File.Exists(b));
        var entries = OperationJournal.Read(res.JournalPath).ToList();
        Assert.Equal(2, entries.Count(e => e.Action == "delete" && e.Success));
    }

    [Fact]
    public void Recycle_mode_uses_recycle_bin_in_batches()
    {
        using var sb = new Sandbox();
        var bin = new FakeRecycleBin();
        var items = Enumerable.Range(0, 5).Select(i => Item(sb.File($"f{i}.tmp", 10))).ToList();
        var res = Remover(sb, bin).Remove(new JunkRemovalRequest { Items = items, Mode = RemovalMode.RecycleBin, BatchSize = 2 });
        Assert.Equal(5, res.Deleted);
        Assert.Equal(5, bin.Received.Count);
        Directory.Delete(bin.Store, true);
    }

    [Fact]
    public void Zip_mode_archives_then_deletes_and_restores()
    {
        using var sb = new Sandbox();
        var a = sb.File(@"x\a.tmp", 1234);
        File.WriteAllText(a, "hello junk");
        var stamp = new DateTime(2025, 5, 5, 5, 5, 5, DateTimeKind.Utc);
        File.SetLastWriteTimeUtc(a, stamp);
        var backup = Path.Combine(sb.Root, "_bak");
        var res = Remover(sb).Remove(new JunkRemovalRequest { Items = new[] { Item(a) }, Mode = RemovalMode.ZipBackup, BackupFolder = backup });

        Assert.Equal(1, res.Deleted);
        Assert.False(File.Exists(a));
        Assert.NotNull(res.ZipPath);
        Assert.Matches(@"^Jnk \d{4}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}_(AM|PM)\.zip$", Path.GetFileName(res.ZipPath));
        Assert.Equal(JunkBackupArchive.Comment, ZipComment.Get(res.ZipPath!));
        Assert.False(JunkBackupArchive.IsLegacyBackup(res.ZipPath!));
        using (var z = ZipFile.OpenRead(res.ZipPath!)) Assert.Equal(2, z.Entries.Count);   // file + manifest

        var journal = Path.Combine(sb.Root, "_journal");
        var (restored, skipped) = JunkBackupArchive.Restore(res.ZipPath!, journalBase: journal);
        Assert.Equal(1, restored);
        Assert.Empty(skipped);
        Assert.Equal("hello junk", File.ReadAllText(a));
        Assert.Equal(stamp, File.GetLastWriteTimeUtc(a));
        Assert.Equal(0, JunkBackupArchive.Restore(res.ZipPath!, journalBase: journal).Restored);   // existing files are not overwritten
    }

    private static readonly DateTime LegacyStamp = new(2024, 1, 2, 3, 4, 6, DateTimeKind.Local);

    /// <summary>Builds an archive the way the original does: entry = full source path, Ace backup comment.</summary>
    private static string LegacyZip(Sandbox sb, params (string EntryName, string Content)[] files)
    {
        var zipPath = Path.Combine(sb.Root, "_ace", "Jnk 2024_01_02_03_04_05_PM.zip");
        Directory.CreateDirectory(Path.GetDirectoryName(zipPath)!);
        using (var z = ZipFile.Open(zipPath, ZipArchiveMode.Create))
            foreach (var (name, content) in files)
            {
                var e = z.CreateEntry(name);
                e.LastWriteTime = new DateTimeOffset(LegacyStamp);   // zip (DOS) time = local clock time, as the original writes it
                using var w = new StreamWriter(e.Open());
                w.Write(content);
            }
        ZipComment.Set(zipPath, "\nThis is an Ace Utilities Backup file; not a normal zip file.\nPlease DO NOT EDIT this file.");
        return zipPath;
    }

    [Fact]
    public void Legacy_ace_backup_is_listed_and_restored_selectively()
    {
        using var sb = new Sandbox();
        var a = Path.Combine(sb.Root, @"orig\a.tmp");
        var b = Path.Combine(sb.Root, @"orig\sub\b.tmp");
        var zip = LegacyZip(sb, (a, "AAA"), (b.Replace('\\', '/'), "BBB"), ("relative.tmp", "x"), (@"C:\x\..\..\evil.tmp", "x"));
        Assert.True(JunkBackupArchive.IsLegacyBackup(zip));

        var list = JunkBackupArchive.List(zip);
        Assert.Equal(4, list.Count);
        Assert.Equal(a, list[0].OriginalPath, ignoreCase: true);
        Assert.Equal(b, list[1].OriginalPath, ignoreCase: true);                 // '/' separators accepted
        Assert.Null(list[2].OriginalPath);                                        // no location: never guessed
        Assert.Null(list[3].OriginalPath);                                        // traversal rejected
        Assert.Contains("..", list[3].Problem);

        var journal = Path.Combine(sb.Root, "_journal");
        var r = JunkBackupArchive.RestoreEntries(zip, new[] { list[0] }, journalBase: journal);   // selective
        Assert.Equal(1, r.Restored);
        Assert.Equal("AAA", File.ReadAllText(a));
        Assert.False(File.Exists(b));
        Assert.Equal(LegacyStamp.ToUniversalTime(), File.GetLastWriteTimeUtc(a));

        r = JunkBackupArchive.RestoreEntries(zip, list, journalBase: journal);
        Assert.Equal(1, r.Restored);                                              // b only; a exists, two unusable
        Assert.Equal(3, r.Skipped.Count);
        Assert.Contains(r.Skipped, s => s.Reason == "exists");
        Assert.Equal("BBB", File.ReadAllText(b));
        Assert.Contains(OperationJournal.Read(r.JournalPath), e => e.Action == "restore" && e.Success);
    }

    [Fact]
    public void Restore_to_other_folder_keeps_structure_and_never_writes_protected_folders()
    {
        using var sb = new Sandbox();
        var a = Path.Combine(sb.Root, @"orig\a.tmp");
        var win = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
        var sys = Path.Combine(win, @"System32\cleansuite_test_never_written.tmp");
        var zip = LegacyZip(sb, (a, "AAA"), (sys, "x"));
        var list = JunkBackupArchive.List(zip);
        var journal = Path.Combine(sb.Root, "_journal");

        var r = JunkBackupArchive.RestoreEntries(zip, list.Take(1).ToList(), targetFolder: Path.Combine(sb.Root, "out"), journalBase: journal);
        var expected = Path.Combine(sb.Root, "out", JunkBackupArchive.EntryNameFor(a).Replace('/', '\\'));
        Assert.Equal(1, r.Restored);
        Assert.Equal("AAA", File.ReadAllText(expected));
        Assert.False(File.Exists(a));

        r = JunkBackupArchive.RestoreEntries(zip, list.Skip(1).ToList(), journalBase: journal);
        Assert.Equal(0, r.Restored);
        Assert.StartsWith("protected system", Assert.Single(r.Skipped).Reason);
        Assert.False(File.Exists(sys));
    }

    [DllImport("kernel32.dll")] private static extern int GetOEMCP();

    [Fact]
    public void Legacy_names_are_decoded_per_entry_flag_oem_or_utf8()
    {
        using var sb = new Sandbox();
        System.Text.Encoding.RegisterProvider(System.Text.CodePagesEncodingProvider.Instance);
        var oem = System.Text.Encoding.GetEncoding(GetOEMCP());
        // A non-ASCII folder name representable in this system's OEM code page (Arabic on cp720, accented Latin elsewhere).
        var folder = new[] { "مجلد", "Grüße", "Ñandú" }.First(c => oem.GetString(oem.GetBytes(c)) == c);
        var oemPath = Path.Combine(sb.Root, folder, "a.tmp");
        var utfPath = Path.Combine(sb.Root, "ملف", "b.tmp");
        var comment = "\nThis is an Ace Utilities Backup file; not a normal zip file.\nPlease DO NOT EDIT this file.";

        var oemZip = Path.Combine(sb.Root, "oem.zip");                       // no UTF-8 flag (as the original writes)
        using (var z = ZipFile.Open(oemZip, ZipArchiveMode.Create, oem)) z.CreateEntry(oemPath);
        ZipComment.Set(oemZip, comment);
        var utfZip = Path.Combine(sb.Root, "utf.zip");                       // UTF-8 flag set
        using (var z = ZipFile.Open(utfZip, ZipArchiveMode.Create)) z.CreateEntry(utfPath);
        ZipComment.Set(utfZip, comment);

        Assert.Equal(oemPath, Assert.Single(JunkBackupArchive.List(oemZip)).OriginalPath);
        Assert.Equal(utfPath, Assert.Single(JunkBackupArchive.List(utfZip)).OriginalPath);
        var r = JunkBackupArchive.RestoreEntries(utfZip, JunkBackupArchive.List(utfZip), journalBase: Path.Combine(sb.Root, "_journal"));
        Assert.Equal(1, r.Restored);
        Assert.True(File.Exists(utfPath));
    }

    [Fact]
    public void Non_backup_zip_is_rejected()
    {
        using var sb = new Sandbox();
        var zip = Path.Combine(sb.Root, "plain.zip");
        using (var z = ZipFile.Open(zip, ZipArchiveMode.Create)) z.CreateEntry("x.txt");
        Assert.Throws<InvalidDataException>(() => JunkBackupArchive.List(zip));
    }

    [Fact]
    public void Journal_sessions_started_together_do_not_collide()
    {
        using var sb = new Sandbox();
        var j = Path.Combine(sb.Root, "_journal");
        var journals = Enumerable.Range(0, 5).Select(_ => new OperationJournal("same", j)).ToList();
        Assert.Equal(5, journals.Select(x => x.FilePath).Distinct(StringComparer.OrdinalIgnoreCase).Count());
        journals.ForEach(x => x.Dispose());
    }

    [Fact]
    public void Changed_or_protected_files_are_not_deleted()
    {
        using var sb = new Sandbox();
        var changed = sb.File("changed.tmp", 10);
        var item = Item(changed);
        File.WriteAllBytes(changed, new byte[99]);                                 // modified after scan
        var guarded = sb.File(@"guard\keep.tmp", 10);
        var prot = new ProtectedPaths().AddTree(Path.Combine(sb.Root, "guard"));
        var res = new JunkRemover(new FakeRecycleBin(), prot, Path.Combine(sb.Root, "_journal"))
            .Remove(new JunkRemovalRequest { Items = new[] { item, Item(guarded) }, Mode = RemovalMode.Permanent });
        Assert.Equal(0, res.Deleted);
        Assert.True(File.Exists(changed) && File.Exists(guarded));
        Assert.Contains(res.Failed, f => f.Reason == "changed since scan");
        Assert.Contains(res.Failed, f => f.Reason.StartsWith("protected", StringComparison.Ordinal));
    }

    [Fact]
    public void Empty_temp_subfolders_removed_but_not_the_temp_root()
    {
        using var sb = new Sandbox();
        var temp = Path.Combine(sb.Root, "temp");
        Directory.CreateDirectory(Path.Combine(temp, @"e1\e2"));
        var keep = sb.File(@"temp\full\keep.txt", 1);
        var res = Remover(sb).Remove(new JunkRemovalRequest
        { Items = Array.Empty<JunkItem>(), Mode = RemovalMode.Permanent, TempFolders = new[] { temp }, DeleteEmptyTempFolders = true });
        Assert.Equal(2, res.EmptyFoldersRemoved);
        Assert.True(Directory.Exists(temp));
        Assert.True(File.Exists(keep));
        Assert.False(Directory.Exists(Path.Combine(temp, "e1")));
    }

    [Fact]
    public void Protected_paths_guard_system_locations()
    {
        var p = ProtectedPaths.ForCurrentSystem();
        var win = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
        Assert.NotNull(p.Check(Path.Combine(win, @"System32\kernel32.dll")));
        Assert.NotNull(p.Check(win, true));
        Assert.NotNull(p.Check(@"C:\"));
        Assert.Null(p.Check(Path.Combine(win, @"Temp\x.tmp")));
    }
}
